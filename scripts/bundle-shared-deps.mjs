#!/usr/bin/env node
/**
 * popup / sidepanel 共享依赖打包（L1 性能优化，针对 Windows SmartScreen / AV 慢路径）
 *
 * 背景：低配 Windows 上每个 `<script src=>` 元素加载都会过 Microsoft SmartScreen
 * 或第三方安全软件的"出处校验"，每条 ~800ms 固定成本。Mac 0 此问题。
 * 实测：Mac DCL 18ms / Windows DCL 4248ms，差 226 倍；同样文件 fetch() 都是
 * 5ms 量级。瓶颈纯粹在 `<script>` 标签数量。
 *
 * 做法：把 popup.html 里 5 个完整逻辑 `<script>` 拼成 1 个 popup.bundle.js，
 * 再让 HTML 只加载很小的 popup.boot.js。boot 负责首屏和基础点击，完整 bundle
 * 在首屏之后动态加载。sidepanel 同款。
 *
 * 关键点：
 *  - shared/*.js + popup.js / sidepanel.js 仍各自独立，方便单文件 review / debug
 *  - 支持传入 "." 生成源码目录 bundle，方便直接加载未打包扩展时也走快路径
 *  - 默认处理 build/chrome-mv3-prod，保证正式产物也走快路径
 *  - 拼接顺序与 popup.html / sidepanel.html 里 script 标签顺序完全一致，确保
 *    globalThis.CCSLogger / CCSRuntimeClient / CCSStorageDefaults / CCSKeywordClient
 *    在 popup/sidepanel.js 运行前已经挂好
 *  - 三个 shared IIFE 都是 `(function(){'use strict'; ...})();` 自封闭，concat 后无作用域污染
 *
 * 验证产物：build/chrome-mv3-prod/popup/popup.bundle.js 与 build/chrome-mv3-prod/popup/popup.html
 * （后者已被改写为只引用 popup.bundle.js）。Sidepanel 同。
 */

import fs from "node:fs"
import path from "node:path"
import process from "node:process"

const root = process.cwd()
const buildDir = path.resolve(root, process.argv[2] || "build/chrome-mv3-prod")

const POPUP_DEPS = [
  "shared/logger.js",
  "shared/runtimeClient.js",
  "shared/storageDefaults.js",
  "shared/keywordClient.js",
  "popup/popup.js"
]

const SIDEPANEL_DEPS = [
  "shared/logger.js",
  "shared/runtimeClient.js",
  "shared/storageDefaults.js",
  "shared/keywordClient.js",
  "sidepanel/sidepanel.js"
]

function bundleFiles(deps, label) {
  const parts = []
  parts.push(`/**\n * 触触搜 ${label}.bundle.js (auto-generated by scripts/bundle-shared-deps.mjs)\n`)
  parts.push(` * Concat of (in order):\n`)
  deps.forEach((d) => parts.push(` *   - ${d}\n`))
  parts.push(` * Do not edit. Source files unchanged; this is build-time only.\n */\n\n`)
  for (const rel of deps) {
    const absPath = path.join(root, rel)
    if (!fs.existsSync(absPath)) {
      throw new Error(`bundle dep missing: ${rel}`)
    }
    const content = fs.readFileSync(absPath, "utf8")
    parts.push(`/* ============================================================\n`)
    parts.push(` * BEGIN ${rel}\n`)
    parts.push(` * ============================================================ */\n`)
    parts.push(content)
    if (!content.endsWith("\n")) parts.push("\n")
    parts.push(`/* ============================================================\n`)
    parts.push(` * END ${rel}\n`)
    parts.push(` * ============================================================ */\n\n`)
  }
  return parts.join("")
}

// 找到 popup.html / sidepanel.html 里那 5 个 <script> 块，整体替换成 boot
// 引用。锚点：第一个 <script ... shared/logger.js ...> 开始，到最后的
// <script ... popup.js / sidepanel.js ...> 的 </script> 结束。
function patchHtml(htmlPath, mainScriptName, entryHref, bundleHref) {
  if (!fs.existsSync(htmlPath)) {
    console.warn(`[bundle-shared-deps] HTML 不存在，跳过: ${htmlPath}`)
    return false
  }
  let html = fs.readFileSync(htmlPath, "utf8")

  const sharedLoggerIdx = html.indexOf('<script src="../shared/logger.js"')
  if (sharedLoggerIdx === -1) {
    const entryAsyncTag = `<script src="${entryHref}" async></script>`
    const entryDeferTag = `<script src="${entryHref}" defer></script>`
    const bundleAsyncTag = `<script src="${bundleHref}" async></script>`
    const bundleDeferTag = `<script src="${bundleHref}" defer></script>`
    if (html.includes(entryAsyncTag)) {
      return true
    }
    if (html.includes(entryDeferTag)) {
      fs.writeFileSync(htmlPath, html.replace(entryDeferTag, entryAsyncTag), "utf8")
      return true
    }
    if (html.includes(bundleAsyncTag) || html.includes(bundleDeferTag)) {
      html = html.replace(bundleAsyncTag, entryAsyncTag).replace(bundleDeferTag, entryAsyncTag)
      fs.writeFileSync(htmlPath, html, "utf8")
      return true
    }
    // 已 patch 过 / HTML 模板不同 / dev 路径不一致
    console.warn(`[bundle-shared-deps] ${htmlPath} 找不到 shared/logger.js 引用，跳过（可能已 patched）`)
    return false
  }
  const mainScriptTag = `<script src="${mainScriptName}"`
  const mainIdx = html.indexOf(mainScriptTag, sharedLoggerIdx)
  if (mainIdx === -1) {
    console.warn(`[bundle-shared-deps] ${htmlPath} 找不到 ${mainScriptTag}，跳过`)
    return false
  }
  const closeIdx = html.indexOf("</script>", mainIdx)
  if (closeIdx === -1) return false

  // 找到块开头之前的行起始位置（保留行缩进的美观）
  let blockStart = sharedLoggerIdx
  while (blockStart > 0 && html[blockStart - 1] !== "\n") blockStart--

  // 找到 </script> 之后到行尾
  const blockEnd = closeIdx + "</script>".length

  const replacement = `<script src="${entryHref}" async></script>`
  // 保留原本的行首缩进
  const indent = html.slice(blockStart, sharedLoggerIdx)
  const newHtml = html.slice(0, blockStart) + indent + replacement + html.slice(blockEnd)
  fs.writeFileSync(htmlPath, newHtml, "utf8")
  return true
}

function main() {
  if (!fs.existsSync(buildDir)) {
    console.warn(`[bundle-shared-deps] build dir 不存在，跳过: ${buildDir}`)
    process.exit(0)
  }

  // === popup ===
  try {
    const popupBundle = bundleFiles(POPUP_DEPS, "popup")
    const popupBundlePath = path.join(buildDir, "popup", "popup.bundle.js")
    fs.writeFileSync(popupBundlePath, popupBundle, "utf8")
    const popupHtmlPath = path.join(buildDir, "popup", "popup.html")
    if (patchHtml(popupHtmlPath, "popup.js", "popup.boot.js", "popup.bundle.js")) {
      console.log(
        `[bundle-shared-deps] ✓ popup: full bundle ready (${(popupBundle.length / 1024).toFixed(1)}KB), HTML uses boot`
      )
    }
  } catch (e) {
    console.warn(`[bundle-shared-deps] popup bundle 失败: ${e?.message || e}`)
  }

  // === sidepanel ===
  try {
    const sidepanelBundle = bundleFiles(SIDEPANEL_DEPS, "sidepanel")
    const sidepanelBundlePath = path.join(buildDir, "sidepanel", "sidepanel.bundle.js")
    fs.writeFileSync(sidepanelBundlePath, sidepanelBundle, "utf8")
    const sidepanelHtmlPath = path.join(buildDir, "sidepanel", "sidepanel.html")
    if (patchHtml(sidepanelHtmlPath, "sidepanel.js", "sidepanel.boot.js", "sidepanel.bundle.js")) {
      console.log(
        `[bundle-shared-deps] ✓ sidepanel: full bundle ready (${(sidepanelBundle.length / 1024).toFixed(1)}KB), HTML uses boot`
      )
    }
  } catch (e) {
    console.warn(`[bundle-shared-deps] sidepanel bundle 失败: ${e?.message || e}`)
  }
}

main()
